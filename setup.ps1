# =============================================================
# MOSIP — ID Generator Service — Automated Setup Script
# =============================================================
# Run this script once from the directory where you cloned this repo.
#
# What it does:
#   1. Clones the MOSIP commons repository
#   2. Generates application-local.properties with all config
#   3. Builds the kernel-idgenerator-service with Maven
#   4. Starts the service
#
# Usage:
#   .\setup.ps1
#
# Optional flags:
#   -SkipClone    Skip cloning (use if you already cloned commons)
#   -SkipBuild    Skip Maven build (use if already built)
#   -NoBoot       Don't start the service after build
# =============================================================

param(
    [switch]$SkipClone,
    [switch]$SkipBuild,
    [switch]$NoBoot
)

$ErrorActionPreference = "Stop"
$Root    = $PSScriptRoot
$Version = "1.3.0"
$Port    = "8080"
$ServiceDir = "$Root\commons\kernel\kernel-idgenerator-service"
$JarPath    = "$ServiceDir\target\kernel-idgenerator-service-$Version.jar"

# ---------------------------------------------------------------
# Helper
# ---------------------------------------------------------------
function Write-Step($n, $msg) {
    Write-Host ""
    Write-Host "[$n] $msg" -ForegroundColor Cyan
    Write-Host ("-" * 55) -ForegroundColor DarkGray
}

function Assert-Tool($cmd, $hint) {
    if (-not (Get-Command $cmd -ErrorAction SilentlyContinue)) {
        Write-Host "ERROR: '$cmd' not found. $hint" -ForegroundColor Red
        exit 1
    }
}

# ---------------------------------------------------------------
# 0. Check prerequisites
# ---------------------------------------------------------------
Write-Host ""
Write-Host "=======================================================" -ForegroundColor Magenta
Write-Host "   MOSIP ID Generator — Automated Setup" -ForegroundColor Magenta
Write-Host "=======================================================" -ForegroundColor Magenta

Write-Step "0" "Checking prerequisites..."
Assert-Tool "java"  "Install JDK 21 from https://adoptium.net"
Assert-Tool "mvn"   "Install Maven 3.6+ from https://maven.apache.org/download.cgi"
Assert-Tool "git"   "Install Git from https://git-scm.com"

$javaVer = java -version 2>&1 | Select-String "version" | Out-String
$mvnVer  = mvn -version 2>&1 | Select-String "Apache Maven" | Out-String
Write-Host "  Java : $($javaVer.Trim())" -ForegroundColor Green
Write-Host "  Maven: $($mvnVer.Trim())" -ForegroundColor Green

# ---------------------------------------------------------------
# 1. Clone MOSIP commons
# ---------------------------------------------------------------
Write-Step "1" "Cloning MOSIP commons repository..."

if ($SkipClone) {
    Write-Host "  --SkipClone set. Using existing commons folder." -ForegroundColor Yellow
} elseif (Test-Path "$Root\commons") {
    Write-Host "  commons/ already exists. Skipping clone." -ForegroundColor Yellow
    Write-Host "  (Delete the commons/ folder and re-run to get a fresh clone)" -ForegroundColor DarkGray
} else {
    Write-Host "  Cloning from https://github.com/mosip/commons.git ..." -ForegroundColor Gray
    git clone --depth 1 --branch master https://github.com/mosip/commons.git "$Root\commons"
    if ($LASTEXITCODE -ne 0) {
        Write-Host "  ERROR: Clone failed. Check your internet connection." -ForegroundColor Red
        exit 1
    }
    Write-Host "  Cloned successfully." -ForegroundColor Green
}

# ---------------------------------------------------------------
