Write-Host "    Metrics : http://localhost:$Port/v1/idgenerator/actuator/prometheus" -ForegroundColor Cyan
Write-Host ""
Write-Host "  Press Ctrl+C to stop." -ForegroundColor DarkYellow
Write-Host ""

java -jar "$JarPath"
