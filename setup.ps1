# Create the resources dir if it doesn't exist yet
$propsDir = Split-Path $propsPath
if (-not (Test-Path $propsDir)) {
    New-Item -ItemType Directory -Path $propsDir | Out-Null
}

Set-Content -Path $propsPath -Value $config -Encoding UTF8
Write-Host "  Written: $propsPath" -ForegroundColor Green

# ---------------------------------------------------------------
# 3. Build with Maven
# ---------------------------------------------------------------
Write-Step "3" "Building with Maven (this may take a few minutes)..."

if ($SkipBuild) {
    Write-Host "  --SkipBuild set. Skipping Maven build." -ForegroundColor Yellow
    if (-not (Test-Path $JarPath)) {
        Write-Host "  ERROR: JAR not found at $JarPath" -ForegroundColor Red
        Write-Host "  Run without -SkipBuild to build first." -ForegroundColor Red
        exit 1
    }
} else {
    Push-Location "$Root\commons"
    try {
        mvn clean install -pl kernel/kernel-idgenerator-service -am -DskipTests
        if ($LASTEXITCODE -ne 0) {
            Write-Host "  ERROR: Maven build failed." -ForegroundColor Red
            exit 1
        }
    } finally {
        Pop-Location
    }
    Write-Host "  Build successful." -ForegroundColor Green
}

# ---------------------------------------------------------------
# 4. Start the service
# ---------------------------------------------------------------
Write-Step "4" "Starting the ID Generator Service..."

if ($NoBoot) {
    Write-Host "  --NoBoot set. Not starting the service." -ForegroundColor Yellow
    Write-Host ""
    Write-Host "  To start manually, run:" -ForegroundColor White
    Write-Host "  java -jar `"$JarPath`"" -ForegroundColor Cyan
    exit 0
}

Write-Host ""
Write-Host "  Service starting on http://localhost:$Port/v1/idgenerator" -ForegroundColor Magenta
Write-Host ""
